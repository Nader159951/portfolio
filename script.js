// Network topology canvas
// =========================================================

(function topology() {

  const canvas =
    document.getElementById("topology");

  if (!canvas) {
    return;
  }


  const ctx =
    canvas.getContext("2d");


  let w;
  let h;
  let dpr;

  let nodes = [];


  const NODE_COUNT_BASE = 46;


  const mouse = {
    x: -9999,
    y: -9999
  };


  function themeColors() {

    const cs =
      getComputedStyle(
        document.documentElement
      );


    return {

      line:
        cs.getPropertyValue(
          "--topology-line"
        ).trim() ||
        "139,150,166",

      amber:
        cs.getPropertyValue(
          "--topology-amber"
        ).trim() ||
        "232,163,61",

      teal:
        cs.getPropertyValue(
          "--topology-teal"
        ).trim() ||
        "79,216,196"

    };

  }


  function resize() {

    dpr =
      Math.min(
        window.devicePixelRatio || 1,
        2
      );


    w =
      canvas.offsetWidth;

    h =
      canvas.offsetHeight;


    canvas.width =
      w * dpr;

    canvas.height =
      h * dpr;


    ctx.setTransform(
      dpr,
      0,
      0,
      dpr,
      0,
      0
    );


    seedNodes();

  }


  function seedNodes() {

    const count =
      Math.min(
        NODE_COUNT_BASE,
        Math.floor(
          (w * h) / 26000
        )
      );


    nodes =
      Array.from(
        {
          length:
            Math.max(count, 18)
        },
        () => ({

          x:
            Math.random() * w,

          y:
            Math.random() * h,

          vx:
            (Math.random() - 0.5) *
            0.18,

          vy:
            (Math.random() - 0.5) *
            0.18,

          r:
            Math.random() < 0.18
              ? 3.4
              : 1.8,

          kind:
            Math.random() < 0.5
              ? "amber"
              : "teal"

        })
      );

  }


  function step() {

    const colors =
      themeColors();


    ctx.clearRect(
      0,
      0,
      w,
      h
    );


    nodes.forEach(n => {

      n.x += n.vx;
      n.y += n.vy;


      if (
        n.x < 0 ||
        n.x > w
      ) {
        n.vx *= -1;
      }


      if (
        n.y < 0 ||
        n.y > h
      ) {
        n.vy *= -1;
      }

    });


    const maxDist =
      Math.min(
        150,
        w / 5
      );


    for (
      let i = 0;
      i < nodes.length;
      i++
    ) {

      for (
        let j = i + 1;
        j < nodes.length;
        j++
      ) {

        const a = nodes[i];
        const b = nodes[j];


        const dx =
          a.x - b.x;

        const dy =
          a.y - b.y;


        const dist =
          Math.sqrt(
            dx * dx +
            dy * dy
          );


        if (dist < maxDist) {

          const alpha =
            (1 - dist / maxDist) *
            0.18;


          ctx.strokeStyle =
            `rgba(${colors.line},${alpha})`;

          ctx.lineWidth = 1;


          ctx.beginPath();

          ctx.moveTo(
            a.x,
            a.y
          );

          ctx.lineTo(
            b.x,
            b.y
          );

          ctx.stroke();

        }

      }


      const dxm =
        nodes[i].x -
        mouse.x;

      const dym =
        nodes[i].y -
        mouse.y;


      const dm =
        Math.sqrt(
          dxm * dxm +
          dym * dym
        );


      if (dm < 180) {

        ctx.strokeStyle =
          `rgba(${colors.amber},${(1 - dm / 180) * 0.4})`;


        ctx.beginPath();

        ctx.moveTo(
          nodes[i].x,
          nodes[i].y
        );

        ctx.lineTo(
          mouse.x,
          mouse.y
        );

        ctx.stroke();

      }

    }


    nodes.forEach(n => {

      ctx.beginPath();


      ctx.fillStyle =
        n.kind === "amber"
          ? `rgba(${colors.amber},0.6)`
          : `rgba(${colors.teal},0.6)`;


      ctx.arc(
        n.x,
        n.y,
        n.r,
        0,
        Math.PI * 2
      );


      ctx.fill();

    });


    requestAnimationFrame(step);

  }


  window.addEventListener(
    "resize",
    resize
  );


  canvas.addEventListener(
    "mousemove",
    e => {

      const rect =
        canvas.getBoundingClientRect();


      mouse.x =
        e.clientX -
        rect.left;


      mouse.y =
        e.clientY -
        rect.top;

    }
  );


  canvas.addEventListener(
    "mouseleave",
    () => {

      mouse.x = -9999;
      mouse.y = -9999;

    }
  );


  resize();


  if (!reduceMotion) {

    requestAnimationFrame(step);

  } else {

    step();

  }

})();