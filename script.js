// =========================================================
// Language handling
// =========================================================

function detectLang() {
  const saved = localStorage.getItem("lang");

  if (saved === "en" || saved === "ar") {
    return saved;
  }

  return navigator.language &&
         navigator.language.startsWith("ar")
    ? "ar"
    : "en";
}


function applyLang(lang) {

  document.documentElement.setAttribute("lang", lang);

  document.documentElement.setAttribute(
    "dir",
    lang === "ar" ? "rtl" : "ltr"
  );

  document.querySelectorAll("[data-i18n]").forEach(el => {

    const key = el.getAttribute("data-i18n");

    const entry = TRANSLATIONS[key];

    if (entry && entry[lang] != null) {
      el.innerHTML = entry[lang];
    }

  });

  // Update page title
  if (TRANSLATIONS["meta.title"]) {
    document.title = TRANSLATIONS["meta.title"][lang];
  }

  localStorage.setItem("lang", lang);
}


// =========================================================
// Remove leftover template placeholders
// =========================================================

function removeEditPlaceholders() {

  const placeholderPattern =
    /\[\s*EDIT\s*:[^\]]*\]/gi;

  const walker = document.createTreeWalker(
    document.body,
    NodeFilter.SHOW_TEXT
  );

  const textNodes = [];

  let node;

  while ((node = walker.nextNode())) {

    if (placeholderPattern.test(node.nodeValue)) {
      textNodes.push(node);
    }

    placeholderPattern.lastIndex = 0;
  }

  textNodes.forEach(textNode => {

    textNode.nodeValue =
      textNode.nodeValue
        .replace(placeholderPattern, "")
        .replace(/\s{2,}/g, " ")
        .trim();

  });
}


